/* ------------------------------------------------------------------ */
export function compileSections(a: Analysis, input: GenerateInput): CompiledSection[] {
  const groups: { key: string; drafts: Draft[] }[] = [
    { key: "prompt", drafts: promptPillar(a, input) },
    { key: "context", drafts: contextPillar(a) },
    { key: "harness", drafts: harnessPillar(a) },
    { key: "loop", drafts: loopPillar(a) },
    { key: "graph", drafts: graphPillar(a) },
  ];

  const out: CompiledSection[] = [];
  groups.forEach((group, gi) => {
    group.drafts.forEach((d, di) => {
      out.push({
        pillarKey: group.key,
        pillarLabel: pillarLabel(group.key),
        pillarOrder: gi + 1,
        sectionKey: d.key,
        sectionOrder: di + 1,
        titleTh: d.th,
        titleEn: d.en,
        summary: d.summary,
        body: d.body,
        promptSnippet: d.snippet,
        checklist: d.checklist,
        antiPatterns: d.antiPatterns,
        tokenEstimate: estTokens(d.body + d.snippet),
      });
    });
  });
  return out;
}
